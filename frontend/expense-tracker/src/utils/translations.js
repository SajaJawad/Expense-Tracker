const reverseCategoryTranslationsAr = Object.fromEntries(
  Object.entries(categoryTranslations.ar).map(([en, ar]) => [ar, en])
);

export const translateCategory = (name, lang = 'ar') => {
  if (!name) return "";
  if (lang === 'ar') {
    return categoryTranslations.ar[name] || name;
  } else if (lang === 'en') {
    return reverseCategoryTranslationsAr[name] || name;
  }
  return name;
};

export const translateInsight = (text, lang = 'ar') => {
  if (!text || lang !== 'ar') return text;

  // You spent X% more this month than last month.
  let match = text.match(/You spent (\d+)% more this month than last month\./i);
  if (match) {
    return `أنفقت ${match[1]}% أكثر هذا الشهر مقارنة بالشهر الماضي.`;
  }

  // You spent X% less this month than last month.
  match = text.match(/You spent (\d+)% less this month than last month\./i);
  if (match) {
    return `أنفقت ${match[1]}% أقل هذا الشهر مقارنة بالشهر الماضي.`;
  }

  // X is your largest spending category.
  match = text.match(/(.+) is your largest spending category\./i);
  if (match) {
    const translatedCat = translateCategory(match[1].trim(), 'ar');
    return `تعد فئة "${translatedCat}" هي الفئة الأكثر إنفاقاً لديك.`;
  }

  // You have used X% of your monthly budget.
  match = text.match(/You have used (\d+)% of your monthly budget\./i);
  if (match) {
    return `استهلكت ${match[1]}% من ميزانيتك الشهرية.`;
  }

  // Your savings rate this month is X%.
  match = text.match(/Your savings rate this month is (\d+)%\./i);
  if (match) {
    return `معدل إدخارك هذا الشهر هو ${match[1]}%.`;
  }

  return text;
};

export const formatLocalizedDate = (dateStr, lang = 'ar') => {
  if (!dateStr) return "";
  const d = new Date(dateStr);
  if (isNaN(d.getTime())) return dateStr;

  if (lang === 'ar') {
    return d.toLocaleDateString('ar-EG', { day: 'numeric', month: 'long', year: 'numeric' });
  } else {
    return d.toLocaleDateString('en-US', { day: 'numeric', month: 'short', year: 'numeric' });
  }
};
